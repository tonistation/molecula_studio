async function renderedStreams(path: string) {
  const { stdout } = await promisify(execFile)(resolve('node_modules/.bin/remotion'),
    ['ffprobe', '-v', 'error', '-show_streams', '-show_format', '-of', 'json', path]);
  const metadata = JSON.parse(stdout);
  const video = metadata.streams.find((stream: { codec_type: string }) => stream.codec_type === 'video');
  assert.equal(video.codec_name, 'h264');
  assert.equal(video.width, 1080); assert.equal(video.height, 1920);
  assert.equal(video.avg_frame_rate, '30/1'); assert.equal(Number(video.nb_frames), 60);
  assert.ok(Math.abs(Number(metadata.format.duration) - 2) <= 1 / 30);
  return metadata.streams as { codec_type: string; codec_name: string }[];
}

test('stale voice: one edited scene, guarded regeneration, cancel/confirm export and immutable history', { timeout: 240_000 }, async t => {
  let providerRequests = 0;
  const fake = createServer((req, res) => { providerRequests++; req.resume(); res.writeHead(500).end('{}'); });
  await new Promise<void>(resolve => fake.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>(resolve => fake.close(() => resolve())));
  await withStudio(t, async ({ page, root, consoleErrors, resourceErrors }) => {
    page.setDefaultTimeout(15000);
    await page.setViewportSize({ width: 1280, height: 1000 });
    const parsed = parseProjectText(fixtureText('storyboard'));
    assert.ok(parsed.ok);
    const project = parsed.project;
    voicedFixture(project);
    project.scenes.forEach(scene => { scene.audio = null; scene.words = []; });
    project.assets = [];
    await page.getByLabel('JSON externo').setInputFiles({ name: 'project.json', mimeType: 'application/json', buffer: Buffer.from(serializeProject(project)) });
    const voice = page.getByRole('region', { name: 'Voz manual', exact: true });
    await voice.getByLabel('Licencia o permiso de uso del audio').fill('Señal propia para prueba');
    for (const index of [1, 2]) {
      await voice.getByLabel(`Subir audio · escena ${index}`).setInputFiles({ name: 'tone.wav', mimeType: 'audio/wav', buffer: toneWav(700, index * 440) });
      await voice.getByText(new RegExp(`${index}\\..*lista`)).waitFor();
    }
    const file = join(root, project.projectId, 'project.json');
    const attached = JSON.parse(await readFile(file, 'utf8'));
    await page.getByLabel('Texto').first().fill('Texto nuevo.');
    await voice.getByText(/1\..*Voz desactualizada/).waitFor();
    await voice.getByText(/2\..*lista/).waitFor();
    const regenerate = voice.getByRole('button', { name: 'Regenerar esta escena · escena 1', exact: true });
    assert.equal(await regenerate.isDisabled(), true, 'must save before paid regeneration');
    assert.equal(await voice.getByRole('button', { name: /Regenerar esta escena/ }).count(), 1);
    await page.getByRole('button', { name: 'Guardar', exact: true }).click();
    await page.getByText(/Guardado · rev\./).waitFor();
    await page.getByRole('button', { name: 'Proyectos', exact: true }).click();
    await page.getByRole('button', { name: 'Abrir', exact: true }).click();
    await voice.getByText(/1\..*Voz desactualizada/).waitFor();
    await voice.getByText(/2\..*lista/).waitFor();
    const savedBytes = await readFile(file);
    const saved = JSON.parse(savedBytes.toString());
    assert.deepEqual(saved.scenes[1], attached.scenes[1], 'unaffected scene stays byte-equivalent');
    assert.deepEqual(saved.scenes[0].mediaBindings, attached.scenes[0].mediaBindings);
    assert.deepEqual(saved.scenes[0].audio, attached.scenes[0].audio);
    await regenerate.click();
    const spending = voice.getByRole('region', { name: 'Confirmar generación Vibi', exact: true });
    assert.equal([...saved.scenes[0].text].length, 12);
    assert.equal([...SPANISH_ACCENT_PREFIX].length, 40);
    await spending.getByText('Se enviarán 52 caracteres de 1 escenas a TTS y luego sus audios a STT. Se reemplazará la voz de esas escenas y se guardará el proyecto.', { exact: true }).waitFor();
    await spending.getByText('Configuración: elevenlabs / eleven_v4 / fake-voice. Escena 1: 52 caracteres.', { exact: true }).waitFor();
    await spending.getByText(/Se añade «\[neutral Latin American Spanish accent\]» a cada escena \(40 caracteres por escena, incluido el espacio\)/).waitFor();
    await spending.getByRole('button', { name: 'Confirmar generación y consumo TTS + STT', exact: true }).waitFor();
    assert.equal(providerRequests, 0, 'regenerate first opens existing explicit spending consent');
    await spending.getByRole('button', { name: 'Cancelar generación', exact: true }).click();
    assert.equal(providerRequests, 0, 'cancel never submits TTS or STT');
    assert.deepEqual(await readFile(file), savedBytes, 'cancel preserves saved narration and media bindings');
    const panel = page.getByRole('region', { name: 'Exportar video', exact: true });
    const exportButton = panel.getByRole('button', { name: 'Exportar MP4', exact: true });
    const dialog = page.getByRole('dialog', { name: 'Exportar con voz desactualizada', exact: true });
    let renderPosts = 0;
    page.on('request', req => { if (req.method() === 'POST' && req.url().endsWith('/renders')) renderPosts++; });
    await exportButton.click();
    await dialog.waitFor();
    assert.equal(await dialog.getByRole('listitem').count(), 1);
    assert.match(await dialog.innerText(), /no regenera la voz ni consume créditos TTS o STT/);
    const cancel = dialog.getByRole('button', { name: 'Cancelar exportación', exact: true });
    const confirm = dialog.getByRole('button', { name: 'Exportar con los audios guardados', exact: true });
    assert.equal(await cancel.evaluate(node => node === document.activeElement), true);
    assert.equal(await dialog.evaluate(node => node.matches(':modal')), true, 'native modal makes the editor inert');
    await page.keyboard.press('Tab');
    assert.equal(await confirm.evaluate(node => node === document.activeElement), true);
    await page.keyboard.press('Shift+Tab');
    assert.equal(await cancel.evaluate(node => node === document.activeElement), true);
    if (process.env.STALE_VOICE_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.STALE_VOICE_SCREENSHOT_DIR, 'stale-voice-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    const box = await dialog.boundingBox();
    assert.ok(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= 390 && box.y + box.height <= 844);
    assert.equal(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if (process.env.STALE_VOICE_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.STALE_VOICE_SCREENSHOT_DIR, 'stale-voice-mobile.png') });
    await cancel.click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(renderPosts, 0);
    assert.equal(await exportButton.evaluate(node => node === document.activeElement), true, 'cancel restores focus');
    assert.deepEqual(await readFile(file), savedBytes);
    assert.equal((await readdir(join(root, '.renders')).catch(() => [])).length, 0, 'cancel creates no render output');
    await exportButton.click();
    await dialog.waitFor();
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(renderPosts, 0);
    await exportButton.click();
    await confirm.click();
    await dialog.waitFor({ state: 'hidden' });
    await panel.getByText('Exportación completada', { exact: true }).waitFor({ timeout: 180_000 });
    assert.equal(renderPosts, 1);
    assert.equal(providerRequests, 0, 'export confirmation never authorizes or calls TTS/STT');
    const output = await panel.locator('.export-path').innerText();
    assert.equal((await renderedStreams(output)).find(stream => stream.codec_type === 'audio')?.codec_name, 'aac');
    assert.deepEqual(await readFile(file), savedBytes, 'render never repairs audio, words or historical bindings');
    const reopened = parseProjectText((await readFile(file)).toString());
    assert.ok(reopened.ok);
    assert.deepEqual(Object.values(await voiceStatuses(reopened.project, [])), ['desactualizada', 'lista']);
    await voice.getByText(/1\..*Voz desactualizada/).waitFor();
    await exportButton.click();
    await dialog.waitFor();
    await cancel.click();
    assert.equal(renderPosts, 1, 'confirmation is required again for each export');
    assert.deepEqual(consoleErrors, []);
    assert.deepEqual(resourceErrors, []);
  }, 'chromium', undefined, { apiKey: 'fake-stale-only', voiceId: 'fake-voice', baseUrl: `http://127.0.0.1:${(fake.address() as { port: number }).port}` });
});

test('silent export ignores attached stale voices without warning or persisted changes', { timeout: 240_000 }, async t => {
  await withStudio(t, async ({ page, root, store, consoleErrors, resourceErrors }) => {
    page.setDefaultTimeout(180_000);
    const parsed = parseProjectText(fixtureText('storyboard'));
    assert.ok(parsed.ok);
    const project = parsed.project;
    const audio = voicedFixture(project);
    project.output.voiceMode = 'silent';
    const imported = await store.importProject({ text: serializeProject(project) });
    await store.relinkAsset({ projectId: imported.projectId, assetId: 'voice', bytes: audio, mimeType: 'audio/wav' });
    await page.reload();
    await page.getByRole('button', { name: 'Abrir', exact: true }).click();
    await page.getByRole('navigation', { name: 'Flujo de creación' }).getByText('Listo · Opcional en modo silencioso', { exact: true }).waitFor();
    const file = join(root, imported.projectId, 'project.json');
    const before = await readFile(file);
    const panel = page.getByRole('region', { name: 'Exportar video', exact: true });
    await panel.getByRole('button', { name: 'Exportar MP4', exact: true }).click();
    await panel.getByText('Exportación completada', { exact: true }).waitFor();
    assert.equal((await renderedStreams(await panel.locator('.export-path').innerText())).some(stream => stream.codec_type === 'audio'), false);
    assert.equal(await page.getByRole('dialog').count(), 0, 'no warning about unused audio');
    assert.deepEqual(await readFile(file), before);
    assert.deepEqual(consoleErrors, []);
    assert.deepEqual(resourceErrors, []);
  }, 'chromium');
});
